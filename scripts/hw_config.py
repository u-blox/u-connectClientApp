#!/usr/bin/env python3
"""Validate a board profile (app/boards/*.json) and emit a C header of X-macro pin tables for firmware builds.

Usage: hw_config.py <profile.json> [--out hw_config.h]
"""
import argparse
import json
import re
import sys
from pathlib import Path

PIN = re.compile(r"^P([A-K])(\d{1,2})$")
SINGLE = (("i2c", ("scl", "sda")), ("spi", ("sck", "miso", "mosi", "cs")), ("can", ("rx", "tx")))
KNOWN = {"board", "gpio", "adc", "pwm", "i2c", "spi", "can", "reserved", "emu"}


def pins_of(cfg):
    pins = list(cfg.get("gpio", [])) + list(cfg.get("adc", [])) + [p["pin"] for p in cfg.get("pwm", [])]
    for group, names in SINGLE:
        pins += [cfg[group][n] for n in names if n in cfg.get(group, {})]
    return pins


def validate(cfg):
    errors = [f"unknown key '{k}'" for k in cfg if k not in KNOWN]
    pins = pins_of(cfg)
    for p in pins + list(cfg.get("reserved", [])):
        m = PIN.match(p)
        if not m or int(m.group(2)) > 15:
            errors.append(f"bad pin name '{p}'")
    for p in sorted({p for p in pins if pins.count(p) > 1}):
        errors.append(f"pin {p} is assigned twice")
    for p in sorted(set(pins) & set(cfg.get("reserved", []))):
        errors.append(f"pin {p} is reserved")
    return errors


def x(pin):
    m = PIN.match(pin)
    return f"{m.group(1)}, {int(m.group(2))}"


def header(cfg):
    out = ["/* Generated by scripts/hw_config.py - do not edit. */", "#pragma once", "",
           f'#define HW_BOARD_NAME "{cfg["board"]}"', ""]
    out.append("#define HW_GPIO_LIST(X) \\")
    out += [f"    X({x(p)}) \\" for p in cfg.get("gpio", [])] + [""]
    out.append("#define HW_ADC_LIST(X) \\")
    out += [f"    X({x(p)}) \\" for p in cfg.get("adc", [])] + [""]
    out.append("#define HW_PWM_LIST(X) \\")
    out += [f"    X({x(p['pin'])}, {p['timer']}) \\" for p in cfg.get("pwm", [])] + [""]
    for group, names in SINGLE:
        for n in names:
            if n in cfg.get(group, {}):
                out.append(f"#define HW_{group.upper()}_{n.upper()} {x(cfg[group][n])}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("profile")
    ap.add_argument("--out")
    args = ap.parse_args()
    cfg = json.loads(Path(args.profile).read_text(encoding="utf-8"))
    errors = validate(cfg)
    if errors:
        sys.exit(f"{args.profile}: " + "; ".join(errors))
    if args.out:
        Path(args.out).write_text(header(cfg), encoding="utf-8")


if __name__ == "__main__":
    main()
